# Uygula
guncellenen = 0
for l in lex:
    form = l.get("form", "")
    root_ids = l.get("rootIds", [])
    if "R-GU" not in root_ids:
        continue

    # Eğer CIKAR'da varsa çıkar
    if form in CIKAR:
        root_ids.remove("R-GU")
        guncellenen += 1
        l["rootIds"] = root_ids
    # Eğer KALACAK'ta yoksa ve CIKAR'da da yoksa, şüpheli — kontrol et
    elif form not in KALACAK:
        # Şüpheli: çıkar
        root_ids.remove("R-GU")
        guncellenen += 1
        l["rootIds"] = root_ids

print(f"R-GU'dan çıkarılan: {guncellenen}")

# Son durum
